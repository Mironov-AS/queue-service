"""Word-версии Политики и Согласия для зала ожидания (queue-service, без прод-деплоя)."""
from docx import Document
from docx.shared import Pt
from docx.enum.text import WD_ALIGN_PARAGRAPH

ORG = {
    "name": "[Наименование организации / ИП]",
    "inn": "[ИНН]",
    "ogrn": "[ОГРН / ОГРНИП]",
    "address": "[Юридический адрес]",
    "phone": "[Телефон]",
    "email": "[E-mail]",
    "resp": "[Ф.И.О. ответственного за обработку ПДн]",
}


def base_doc(title):
    doc = Document()
    doc.styles["Normal"].font.name = "Calibri"  # type: ignore[attr-defined]
    doc.styles["Normal"].font.size = Pt(11)  # type: ignore[attr-defined]
    doc.add_heading(title, level=0)
    return doc


def h(doc, text):
    doc.add_heading(text, level=1)


def p(doc, text, bold_prefix=None):
    par = doc.add_paragraph()
    if bold_prefix:
        r = par.add_run(bold_prefix)
        r.bold = True
    par.add_run(text)


def note_placeholders(doc):
    par = doc.add_paragraph()
    r = par.add_run(
        "ВНИМАНИЕ: поля в квадратных скобках заполняются после получения "
        "реквизитов организации. Тексты в электронной очереди и на бумаге "
        "должны совпадать."
    )
    r.bold = True


def build_policy():
    o = ORG
    doc = base_doc("Политика обработки персональных данных")
    p(doc, "Электронная очередь автосервиса. Редакция для экрана саморегистрации и печати в зале ожидания.")
    note_placeholders(doc)
    p(doc, f"Оператор персональных данных: {o['name']}, ИНН {o['inn']}, ОГРН {o['ogrn']}, адрес: {o['address']}, телефон: {o['phone']}, e-mail: {o['email']}.")
    h(doc, "1. Какие данные обрабатываются")
    p(doc, "Для выдачи и обслуживания талона обрабатываются: номер автомобиля, номер талона, услуга, дата и время обращения, статус талона. Имя и телефон посетителя — только если посетитель сам их указал в форме или сообщил администратору для связи по визиту.")
    p(doc, "Специальные категории персональных данных и данные детей для работы очереди не требуются и не запрашиваются. Просим не указывать их в свободных полях.")
    h(doc, "2. Цели обработки")
    p(doc, "1) выдача талона и организация очереди; 2) вызов посетителя и информирование о статусе талона; 3) учёт посещений и контроль качества обслуживания.")
    p(doc, "Данные не используются для рекламных рассылок. Передача персональных данных третьим лицам не осуществляется.")
    h(doc, "3. Правовые основания")
    p(doc, "Обработка осуществляется на основании согласия посетителя на обработку персональных данных (п. 1 ч. 1 ст. 6 и ст. 9 Федерального закона от 27.07.2006 № 152-ФЗ «О персональных данных»), а также действий посетителя по получению талона.")
    p(doc, "Получая талон через экран саморегистрации, посетитель подтверждает, что ознакомился с настоящей Политикой и текстом согласия. При оформлении через администратора согласие может быть оформлено на бумаге.")
    h(doc, "4. Как хранятся и защищаются данные")
    p(doc, "Данные хранятся в информационной системе электронной очереди на сервере оператора на территории Российской Федерации. Доступ имеют только уполномоченные сотрудники в объёме, необходимом для обслуживания очереди.")
    p(doc, "Номер талона на общем экране отображается без фамилии, имени, телефона и номера автомобиля. Полные данные талона доступны только сотруднику и самому посетителю на его экране.")
    p(doc, "Данные талонов текущего дня используются для организации приёма. По истечении 30 дней с даты визита данные, позволяющие идентифицировать посетителя, подлежат удалению либо обезличиванию, если более длительный срок не требуется по закону или для рассмотрения обращения посетителя.")
    h(doc, "5. Права посетителя")
    p(doc, f"Посетитель вправе запросить сведения о своих данных, потребовать их уточнения, отозвать согласие, потребовать прекращения обработки и удаления данных. Обращение направляется оператору: {o['phone']}, {o['email']}, либо передаётся администратору в офисе.")
    p(doc, "Отзыв согласия не влияет на законность обработки до момента отзыва. После отзыва оператор прекращает обработку и удаляет данные в срок не более 30 дней, если сохранение не требуется по закону.")
    h(doc, "6. Контакты")
    p(doc, f"Оператор: {o['name']}. Ответственный за обработку персональных данных: {o['resp']}, {o['phone']}, {o['email']}.")
    return doc


def build_consent():
    o = ORG
    doc = base_doc("Согласие на обработку персональных данных")
    p(doc, "Оформление талона электронной очереди автосервиса.")
    note_placeholders(doc)
    p(doc, f"Я, посетитель автосервиса, нажимая кнопку «Получить талон» на экране саморегистрации (по QR-коду или на терминале в офисе) либо сообщая данные администратору для оформления талона, даю согласие {o['name']} (ИНН {o['inn']}, адрес: {o['address']}) на обработку моих персональных данных на следующих условиях.")
    h(doc, "1. Перечень данных")
    p(doc, "Номер автомобиля; номер талона, услуга, дата и время обращения, статус талона; имя и телефон — только если я сам(а) их указал(а) для связи по визиту.")
    h(doc, "2. Цели и действия")
    p(doc, "Цели: выдача талона, организация очереди, вызов посетителя, учёт посещений. Действия: сбор, запись, систематизация, хранение, уточнение, использование, удаление. Автоматизированная обработка — в информационной системе электронной очереди оператора. Передача третьим лицам не осуществляется.")
    h(doc, "3. Срок действия")
    p(doc, "Согласие действует до обслуживания визита и в течение 30 дней после даты визита, после чего данные, позволяющие меня идентифицировать, удаляются либо обезличиваются, если иное не требуется по закону.")
    h(doc, "4. Отзыв согласия")
    p(doc, f"Я вправе отозвать согласие, обратившись к оператору по телефону {o['phone']}, e-mail {o['email']} либо к администратору в офисе. Оператор прекращает обработку и удаляет данные в срок не более 30 дней, если сохранение не требуется по закону.")
    h(doc, "5. Подтверждение")
    p(doc, "Подтверждаю, что ознакомлен(а) с Политикой обработки персональных данных, согласие дано свободно, своей волей и в своём интересе, данные указаны мною добровольно.")
    p(doc, f"Дата и факт согласия фиксируются системой в момент получения талона. Оператор: {o['name']}, {o['address']}, ИНН {o['inn']}, ОГРН {o['ogrn']}.")
    h(doc, "Подпись (при оформлении через администратора)")
    p(doc, "Ф.И.О.: ________________________ / Подпись: ____________ / Дата: ____________")
    return doc


