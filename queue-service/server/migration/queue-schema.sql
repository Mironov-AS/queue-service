-- Target schema for a migrated single-tenant queue. Apply only to an isolated,
-- empty PostgreSQL database. SQLite date/time values are retained as text so
-- the migration does not silently reinterpret historical timestamps.
CREATE TABLE services (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name TEXT NOT NULL, description TEXT, avg_duration_minutes INTEGER DEFAULT 5,
 priority INTEGER DEFAULT 0, daily_limit INTEGER, active INTEGER DEFAULT 1,
 enabled INTEGER DEFAULT 1, created_at TEXT DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS'),
 is_default INTEGER DEFAULT 0
);
CREATE TABLE tickets (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, number INTEGER NOT NULL,
 date TEXT NOT NULL, service_id INTEGER REFERENCES services(id), status TEXT DEFAULT 'waiting',
 is_priority INTEGER DEFAULT 0, name TEXT, phone TEXT, skip_reason TEXT,
 cancel_reason TEXT, created_at TEXT DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS'),
 called_at TEXT, served_at TEXT, field_values TEXT
);
CREATE TABLE users (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username TEXT UNIQUE NOT NULL,
 password_hash TEXT NOT NULL, role TEXT DEFAULT 'operator',
 created_at TEXT DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS'),
 must_change_password INTEGER DEFAULT 0
);
CREATE TABLE action_logs (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER, username TEXT,
 action TEXT NOT NULL, details TEXT, created_at TEXT DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS')
);
CREATE TABLE settings (key TEXT PRIMARY KEY, value TEXT);
CREATE TABLE service_fields (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, service_id INTEGER REFERENCES services(id),
 label TEXT NOT NULL, field_type TEXT DEFAULT 'text', required INTEGER DEFAULT 0,
 order_index INTEGER DEFAULT 0, created_at TEXT DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS'),
 require_check INTEGER DEFAULT 0
);
CREATE TABLE advertisements (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, file_key TEXT NOT NULL,
 file_type TEXT NOT NULL, mime_type TEXT, duration INTEGER DEFAULT 15, order_index INTEGER DEFAULT 0,
 active INTEGER DEFAULT 1, created_at TEXT DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS'),
 owner_id INTEGER, owner_username TEXT, status TEXT DEFAULT 'approved'
);
CREATE TABLE schema_migrations (version INTEGER PRIMARY KEY, name TEXT NOT NULL,
 applied_at TEXT DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS'));
CREATE INDEX idx_tickets_date ON tickets(date);
CREATE INDEX idx_tickets_date_status ON tickets(date,status);
CREATE INDEX idx_tickets_service_id ON tickets(service_id);
CREATE INDEX idx_action_logs_created ON action_logs(created_at DESC);
