// Подключение предварительной записи к основному серверу очереди.
//
// Очередь продолжает работать на SQLite, запись — на отдельной базе PostgreSQL.
// Модуль включается только явными настройками:
//   BOOKING_ENABLED=true            — разрешить запись на этом сервере;
//   BOOKING_DATABASE_URL=postgresql://… — подключение к базе записи.
//
// Если PostgreSQL недоступен или настройки не заданы, модуль остаётся
// выключенным, а /api/booking продолжает отвечать 503: очередь от записи
// не зависит и работает в любом случае.

const { Pool } = require("pg");
const { bookingRepository, schema: bookingSchema } = require("./bookingRepository");
const { bookingConsent } = require("./bookingConsent");
const { createBookingRouter } = require("../routes/booking");
const { requireAuth } = require("../middleware/requireAuth");
const { requireAdmin } = require("../middleware/requireAdmin");

// Справочник услуг в базе записи нужен для внешнего ключа booking_config →
// services(id). Значения копируются из очереди (SQLite), собственные записи
// в базе записи не создаются. Структура таблицы совпадает с миграционной
// схемой очереди (migration/queue-schema.sql), поэтому одинаковый справочник
// работает и с миграцией на PostgreSQL, и с зеркалированием из SQLite.
const SERVICES_SCHEMA = `
CREATE TABLE IF NOT EXISTS services (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name TEXT NOT NULL,
 description TEXT,
 avg_duration_minutes INTEGER DEFAULT 5,
 priority INTEGER DEFAULT 0,
 daily_limit INTEGER,
 active INTEGER DEFAULT 1,
 enabled INTEGER DEFAULT 1,
 created_at TEXT DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS'),
 is_default INTEGER DEFAULT 0
);`;

function readServices(db) {
	try {
		return db
			.prepare(
				"SELECT id, name, description, active, enabled FROM services WHERE active = 1 ORDER BY id",
			)
			.all();
	} catch {
		return [];
	}
}

async function syncServices(pool, db) {
	const rows = readServices(db);
	for (const s of rows) {
		await pool.query(
			`INSERT INTO services(id,name,description,active,enabled) VALUES($1,$2,$3,$4,$5)
       ON CONFLICT(id) DO UPDATE SET name=EXCLUDED.name,description=EXCLUDED.description,active=EXCLUDED.active,enabled=EXCLUDED.enabled`,
			[
				s.id,
				s.name,
				s.description || null,
				s.active === 0 ? 0 : 1,
				s.enabled === 0 ? 0 : 1,
			],
		);
	}
	const ids = rows.map((s) => s.id);
	// Удалённые в очереди услуги не удаляем: на них ссылаются записи и
	// расписание. Помечаем их неактивными.
	await pool.query(
		`UPDATE services SET active = 0 WHERE id <> ALL($1::int[])`,
		[ids.length ? ids : [0]],
	);
	return rows.length;
}

async function startBooking({ db, logger = console, env = process.env } = {}) {
	if (String(env.BOOKING_ENABLED || "").toLowerCase() !== "true") {
		return { enabled: false, reason: "запись выключена (BOOKING_ENABLED)" };
	}
	const url = env.BOOKING_DATABASE_URL;
	if (!url) {
		return { enabled: false, reason: "не задан BOOKING_DATABASE_URL" };
	}
	const pool = new Pool({
		connectionString: url,
		max: Number(env.BOOKING_POOL_MAX || 5),
		connectionTimeoutMillis: Number(env.BOOKING_CONNECT_TIMEOUT_MS || 5000),
		idleTimeoutMillis: 30000,
		...(env.BOOKING_POOL_OPTIONS
			? { options: env.BOOKING_POOL_OPTIONS }
			: {}),
	});
	try {
		await pool.query("SELECT 1");
		await pool.query(SERVICES_SCHEMA);
		await pool.query(bookingSchema);
		const synced = await syncServices(pool, db);
		const router = createBookingRouter({
			repository: bookingRepository(pool),
			approvedConsent: bookingConsent,
			requireAuth,
			requireAdmin,
		});
		logger.log(
			`[booking] запись включена, справочник услуг синхронизирован (${synced})`,
		);
		return {
			enabled: true,
			router,
			pool,
			syncServices: () => syncServices(pool, db),
			close: () => pool.end(),
		};
	} catch (err) {
		logger.error(
			`[booking] запись не включена: ${err && err.message ? err.message : err}`,
		);
		try {
			await pool.end();
		} catch {
			/* пул уже закрыт */
		}
		return { enabled: false, reason: err && err.message ? err.message : String(err) };
	}
}

// Текущее состояние модуля записи для основного сервера.
// Пока модуль не подтверждён, /api/booking отвечает 503 (fail closed).
let current = null;

function setBookingState(state) {
	current = state;
}

function getBookingState() {
	return current;
}

// Вызывается после изменения справочника услуг: PostgreSQL должен знать о
// новых и изменённых услугах. Ошибка синхронизации не должна ломать
// операцию в очереди.
function notifyServicesChanged() {
	if (!current || !current.enabled || typeof current.syncServices !== "function")
		return;
	current.syncServices().catch((err) => {
		console.error(
			"[booking] синхронизация справочника услуг не удалась:",
			err && err.message ? err.message : err,
		);
	});
}

module.exports = {
	startBooking,
	syncServices,
	SERVICES_SCHEMA,
	setBookingState,
	getBookingState,
	notifyServicesChanged,
};
